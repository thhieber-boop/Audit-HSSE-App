function getLang() {
  return localStorage.getItem("hsse_lang");
}
function setLang(lang) {
  localStorage.setItem("hsse_lang", lang);
}

function t(key, vars) {
  const lang = (typeof CURRENT_LANG !== "undefined" && CURRENT_LANG) || getLang() || "fr";
  const lookup = (dict) => key.split(".").reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), dict);
  let str = lookup(UI_STRINGS[lang]);
  if (str === undefined) str = lookup(UI_STRINGS.fr);
  if (str === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), vars[k]);
    });
  }
  return str;
}
